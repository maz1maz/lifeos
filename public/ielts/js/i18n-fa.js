  function translate(raw) {
    var t = translateCore(raw);
    if (t !== null || !raw || !HAN.test(raw)) return t;
    var lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
    var s = raw.trim().replace(/\s+/g, ' ');
    MISSING[s] = (MISSING[s] || 0) + 1;
    var rest = s.replace(HAN_RUN, ' ').replace(/[　-〿＀-￯]/g, ' ').replace(/\s{2,}/g, ' ').trim();
    return /[A-Za-z0-9؀-ۿ]{2,}/.test(rest) ? lead + rest + trail : '';
  }
