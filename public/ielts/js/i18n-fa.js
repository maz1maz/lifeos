  // English title followed by a Chinese gloss ("Rubber 橡胶") → keep the English only.
  function stripGloss(s) {
    var base = s.replace('（无题目）', '').trim();
    if (!/^[A-Za-z0-9"'\[(‘“]/.test(base)) return null;
    if (!/[A-Za-z]{2,}/.test(base) || /[。！？]/.test(base)) return null;
    var cleaned = base.replace(HAN_RUN, ' ').replace(/\s{2,}/g, ' ').trim();
    return cleaned && !HAN.test(cleaned) ? cleaned : null;
  }

  var EMOJI_LEAD = /^((?:[←-⯿☀-➿️‍]|\ud83c[\udc00-\udfff]|\ud83d[\udc00-\udfff]|\ud83e[\udc00-\udfff])+\s*)(.+)$/;

  // Strict translation: returns null when it can't translate the whole string.
  function translateCore(raw) {
    if (!raw || !HAN.test(raw)) return null;
    var lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
    var s = raw.trim().replace(/\s+/g, ' ');
    var em = s.match(EMOJI_LEAD);
    if (em) {
      var inner = translateCore(em[2]);
      return inner === null ? null : lead + em[1] + inner.trim() + trail;
    }
    if (Object.prototype.hasOwnProperty.call(EXACT, s)) return lead + EXACT[s] + trail;
    for (var i = 0; i < RULES.length; i++) {
      var m = s.match(RULES[i][0]);
      if (m) return lead + RULES[i][1].apply(null, m) + trail;
    }
    if (s.length <= 80) {
      var g = stripGloss(s);
      if (g) return lead + g + trail;
      var f = translateFragments(s);
      // only accept a fragment translation that leaves no Chinese behind
      if (f !== s && !HAN.test(f)) return lead + f + trail;
    }
    return null;
  }

  // Display translation: strict first; otherwise this copy shows only Persian and English,
