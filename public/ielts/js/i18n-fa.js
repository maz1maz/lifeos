  // The app splits labels into several text nodes (e.g. around icons). Translate the
  // joined text of an element's direct text children first, then individual nodes.
  function translateJoined(el) {
    var parts = [];
    for (var c = el.firstChild; c; c = c.nextSibling) {
      if (c.nodeType === 3 && c.nodeValue.trim()) parts.push(c);
    }
    if (parts.length < 2) return;
    var joined = parts.map(function (p) { return p.nodeValue; }).join('');
    var t = translateCore(joined);
    if (t === null) return;
    parts[0].nodeValue = t;
    for (var i = 1; i < parts.length; i++) parts[i].nodeValue = '';
  }

  var ATTRS = ['placeholder', 'title', 'aria-label', 'data-tooltip'];

  function translateNode(node) {
    if (node.nodeType === 3) {
      var p = node.parentNode;
      if (p && (p.nodeName === 'SCRIPT' || p.nodeName === 'STYLE' || p.nodeName === 'TEXTAREA')) return;
      if (p && p.nodeType === 1) translateJoined(p);
      var t = translate(node.nodeValue);
      if (t !== null && t !== node.nodeValue) {
        node.nodeValue = t;
        if (p && p.nodeType === 1 && p.children.length === 0 && !p.hasAttribute('dir')) p.setAttribute('dir', 'auto');
      }
      return;
    }
    if (node.nodeType !== 1) return;
    for (var i = 0; i < ATTRS.length; i++) {
      var v = node.getAttribute && node.getAttribute(ATTRS[i]);
      if (v) { var tv = translate(v); if (tv !== null) node.setAttribute(ATTRS[i], tv); }
    }
    if ((node.nodeName === 'INPUT') && /^(button|submit|reset)$/i.test(node.type || '') && node.value) {
      var bv = translate(node.value); if (bv !== null) node.value = bv;
    }
    translateJoined(node);
    var walker = document.createTreeWalker(node, NodeFilter.SHOW_ALL);
    var n;
    while ((n = walker.nextNode())) {
      if (n.nodeType === 3) translateNode(n);
      else if (n.nodeType === 1) {
        translateJoined(n);
        for (var j = 0; j < ATTRS.length; j++) {
          var av = n.getAttribute(ATTRS[j]);
          if (av) { var ta = translate(av); if (ta !== null) n.setAttribute(ATTRS[j], ta); }
        }
      }
    }
  }

